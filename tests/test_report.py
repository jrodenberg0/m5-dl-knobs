import os

from tests.fixtures.make_fake_results import make


def test_report_has_no_private_or_article_sections(tmp_path, monkeypatch):
    from m5knobs import report
    from m5knobs.figures import architectures, cards, early_stopping, stress
    monkeypatch.setenv("CROSSCHECK_DIR", str(tmp_path))  # old code added a cross-check section when this was set
    res = str(tmp_path / "res")
    make(res)
    fig = str(tmp_path / "fig")
    cards.draw(results_dir=res, out_dir=fig, n_boot=20)
    stress.draw(results_dir=res, out_dir=fig, n_boot=20)
    early_stopping.draw(results_dir=res, out_dir=fig)
    architectures.draw(results_dir=res, out_dir=fig, n_boot=20)
    out = str(tmp_path / "F.md")
    report.write(results_dir=res, out=out)
    text = open(out).read()
    assert "Cross-check" not in text and "CROSSCHECK_DIR" not in text and "article" not in text.lower()
    assert "Generated by `notebooks/06_summary.ipynb` from `results/`." in text
    for section in ("## Run status", "## Setting cards", "## Clipping stress test", "## Early-stopping study",
                    "## Architecture comparison"):
        assert section in text
    if os.path.exists(os.path.join(res, "toy_paths.parquet")):
        assert "## Toy fit" in text


def test_check_derived_fresh(tmp_path):
    import pytest
    from m5knobs import report
    res = tmp_path / "res"
    done = res / "runs" / "a__s1" / "DONE"
    done.parent.mkdir(parents=True)
    done.write_text("")
    os.utime(done, (1000, 1000))
    with pytest.raises(SystemExit, match="run notebooks 03–05 first"):
        report.check_derived_fresh(str(res))
    for f in report.DERIVED:
        (res / f).write_text("{}")
        os.utime(res / f, (2000, 2000))
    report.check_derived_fresh(str(res))
    os.utime(done, (3000, 3000))  # a run finished after the derived files were written
    with pytest.raises(SystemExit, match="card_verdicts.json"):
        report.check_derived_fresh(str(res))


def test_run_status_and_unforecast(tmp_path):
    from m5knobs import report
    from m5knobs.experiments import ARMS
    res = str(tmp_path / "res")
    make(res)
    rs = report.run_status(res)
    assert list(rs.arm) == [a.id for a in ARMS]
    assert set(rs.status) <= {"done", "error", "missing"}
    done = rs[rs.status == "done"]
    assert done.wape.notna().all() and done.bias.notna().all()
    import pandas as pd
    fp = os.path.join(res, "runs", "f2_clip__s1", "forecasts.parquet")
    fc = pd.read_parquet(fp)
    fc[fc.unique_id != "s0"].to_parquet(fp)  # s0 gets no neural forecast at any origin
    act = pd.read_parquet(os.path.join(res, "actuals.parquet"))
    u = report.unforecast(res)
    assert (u["per_min"], u["per_max"]) == (1, 1)
    assert u["units"] == act[act.unique_id == "s0"].y.sum() and u["total"] == act.y.sum()
